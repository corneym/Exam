package au.edu.eq.questionbank.service.workpackage;

import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.Arrays;
import java.util.Comparator;
import java.util.HexFormat;
import java.util.Map;
import java.util.Objects;
import java.util.UUID;

import com.fasterxml.jackson.databind.JsonNode;

import au.edu.eq.questionbank.repository.identity.SqlitePortableContentRepository;
import au.edu.eq.questionbank.repository.identity.SqlitePortableIdentityRepository;
import au.edu.eq.questionbank.repository.identity.SqlitePortableIdentityRepository.EntityType;
import au.edu.eq.questionbank.repository.sqlite.SqliteDatabase;
import au.edu.eq.questionbank.service.workpackage.MasterContributionApprovedImagePreparer.PreparedImage;
import au.edu.eq.questionbank.service.workpackage.MasterContributionDecisionLedger.Choice;
import au.edu.eq.questionbank.service.workpackage.MasterContributionDecisionLedger.RecordDecision;
import au.edu.eq.questionbank.service.workpackage.MasterContributionDecisionLedger.RecordKey;
import au.edu.eq.questionbank.service.workpackage.MasterContributionReviewPlanner.ReviewStatus;

/**
 * Inserts approved new Question PNGs under an active reviewed parent permit.
 *
 * <p>
 * All operations use the caller's SQLite transaction. The parent Question
 * scalar permit and exact owner-specific region permit must already exist.
 * SQLite enforces that requirement through its master capture triggers.
 *
 * <p>
 * New master image identities are generated by the normal portable-identity
 * triggers. The writer retains their mappings to contributor image UUIDs.
 *
 * <p>
 * Existing image replacement, image deletion and managed filesystem publication
 * are not supported.
 */
final class MasterContributionImageWriter {

	private static final byte[] PNG_SIGNATURE = { (byte) 0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A };
	private final SqliteDatabase database;

	MasterContributionImageWriter(SqliteDatabase database) {
		this.database = Objects.requireNonNull(database, "database");
	}

	void insertApproved(Connection connection, ExchangeRecord parent, long parentLocalId,
			Map<RecordKey, RecordDecision> decisions, Map<RecordKey, ExchangeRecord> proposals,
			Map<RecordKey, PreparedImage> prepared, Map<RecordKey, Long> localIds, Map<RecordKey, UUID> canonicalIds)
			throws SQLException {
		Objects.requireNonNull(connection, "connection");
		Objects.requireNonNull(parent, "parent");
		Objects.requireNonNull(decisions, "decisions");
		Objects.requireNonNull(proposals, "proposals");
		Objects.requireNonNull(prepared, "prepared");
		Objects.requireNonNull(localIds, "localIds");
		Objects.requireNonNull(canonicalIds, "canonicalIds");
		if (connection.getAutoCommit()) {
			throw new SQLException("Image application requires a caller-owned transaction");
		}
		if (!"QUESTION".equals(parent.recordType()) || parentLocalId < 1) {
			throw new SQLException("New images require an existing transaction-local " + "parent Question");
		}
		for (PreparedImage image : prepared.values().stream()
				.filter(candidate -> candidate.questionId().equals(parent.recordId()))
				.sorted(Comparator.comparing(candidate -> candidate.imageId().toString())).toList()) {
			RecordKey key = new RecordKey("QUESTION_IMAGE", image.imageId());
			RecordDecision decision = decisions.get(key);
			ExchangeRecord proposal = proposals.get(key);
			if (decision == null || proposal == null || decision.choice() != Choice.QUEUE_APPLY
					|| decision.preliminaryStatus() != ReviewStatus.READY_NEW || decision.baselineRevisionId() != null
					|| decision.masterRevisionId() != null || decision.masterSha256() != null) {
				throw new SQLException("Image is not an approved new contribution: " + image.imageId());
			}
			JsonNode values = proposal.values();
			if (!image.proposedRevisionId().equals(decision.proposedRevisionId())
					|| !image.proposedRevisionId().equals(proposal.revisionId())
					|| !image.questionId().toString().equals(values.path("question_id").asText())
					|| !image.sha256().equals(values.path("image_png").asText())) {
				throw new SQLException("Prepared image differs from reviewed " + "portable evidence");
			}
			byte[] bytes = image.pngBytes();
			if (bytes.length < PNG_SIGNATURE.length
					|| !Arrays.equals(Arrays.copyOf(bytes, PNG_SIGNATURE.length), PNG_SIGNATURE)
					|| !image.sha256().equals(digest(bytes))) {
				throw new SQLException("Prepared PNG bytes failed final verification");
			}
			var identities = new SqlitePortableIdentityRepository(database);
			if (identities.findByPortableId(connection, EntityType.QUESTION_IMAGE, image.imageId()).isPresent()) {
				throw new SQLException("New image portable identity already exists " + "on the master");
			}
			long localId;
			try (PreparedStatement insert = connection.prepareStatement("""
					INSERT INTO question_images (
					    question_id,
					    image_png
					)
					VALUES (?, ?)
					""")) {
				insert.setLong(1, parentLocalId);
				insert.setBytes(2, bytes);
				if (insert.executeUpdate() != 1) {
					throw new SQLException("Approved Question image was not inserted");
				}
			}
			try (PreparedStatement generated = connection.prepareStatement("""
					SELECT last_insert_rowid()
					"""); ResultSet result = generated.executeQuery()) {
				if (!result.next()) {
					throw new SQLException("Inserted image has no SQLite identity");
				}
				localId = result.getLong(1);
				if (localId < 1 || result.next()) {
					throw new SQLException("Invalid inserted image local identity");
				}
			}
			var identity = identities.findByLocalId(connection, EntityType.QUESTION_IMAGE, localId)
					.orElseThrow(() -> new SQLException("Inserted image has no portable identity"));
			ExchangeRecord actual = new SqlitePortableContentRepository(database)
					.snapshot(connection, EntityType.QUESTION_IMAGE, localId).record();
			if (!actual.recordId().equals(identity.portableId())
					|| !actual.values().path("image_png").asText().equals(image.sha256())) {
				throw new SQLException("Inserted image differs from approved PNG");
			}
			if (localIds.putIfAbsent(key, localId) != null
					|| canonicalIds.putIfAbsent(key, identity.portableId()) != null) {
				throw new SQLException("Duplicate canonical image mapping");
			}
		}
	}

	private String digest(byte[] bytes) {
		try {
			return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes));
		} catch (NoSuchAlgorithmException failure) {
			throw new IllegalStateException("SHA-256 is unavailable", failure);
		}
	}
}
